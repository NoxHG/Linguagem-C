#include <stdio.h>

int main(void)
{
    int x = 10;
    int y = 20;
    int z = 0;

    z = x + y;

    printf("%d", z);
    return 0;
}

// Operadores aritimeticos em C:
/*
    + -> Adicao
    - -> Subtracao
    * -> Multiplicacao
    / -> Divisao
    % -> Modulo (resto da divisao)

    diferenca entre / e %:
    / -> retorna o quociente da divisao
    % -> retorna o resto da divisao
*/